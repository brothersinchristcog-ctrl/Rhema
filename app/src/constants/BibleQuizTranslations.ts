/**
 * Localizes a Scripture reference string (e.g. "Genesis 2:21-25" -> "ఆదికాండము 2:21-25")
 */
export function localizeBibleReference(ref: string, lang: SupportedLanguage): string {
  if (!ref || lang === 'en') return ref;
  const bookMap = BIBLE_BOOK_TRANSLATIONS[lang];
  if (!bookMap) return ref;

  for (const [enBook, locBook] of Object.entries(bookMap)) {
    if (ref.startsWith(enBook)) {
      return ref.replace(enBook, locBook);
    }
  }
  return ref;
}

